-- 013 — Seguimiento SIESA: qué mandó el portal, y qué cambió afuera
-- ---------------------------------------------------------------------------
--
-- QUÉ RESUELVE
-- Johan, 2026-10-19: una pestaña del admin para saber "si se insertaron las
-- cosas, si salió error, cuándo se modificó algo en SIESA y qué". El modelo es
-- el panel SIESA de Carnes: UNA FILA POR INTENTO, con lo que viajó y lo que
-- volvió, tal cual.
--
-- POR QUÉ NO ALCANZABA CON LO QUE HABÍA
--   · `pp_solicitud_lineas.siesa_payload/_respuesta/_verificacion` guardan solo
--     el ÚLTIMO intento: `reintentar()` limpia la verificación y el empuje
--     siguiente pisa el payload. El historial se perdía.
--   · `pp_auditoria` es append-only pero genérica: un fallo deja el texto del
--     error, nunca el payload; un éxito no deja ni payload ni respuesta.
--
-- DOS TABLAS, DOS PREGUNTAS
--   pp_siesa_envios  → "¿qué le mandamos a SIESA, cuándo, y qué contestó?"
--                       La escribe `empujarLote()` (el único camino al conector).
--   pp_siesa_cambios → "¿qué cambió en las cotizaciones de SIESA, y fuimos
--                       nosotros?" La escribe el snapshot diario, comparando la
--                       corrida nueva contra la tabla antes de pisarla.
--
-- LO QUE pp_siesa_cambios NO PUEDE SABER (dicho para que nadie lo prometa)
--   · CUÁNDO exacto: el snapshot corre una vez por día. Un cambio se ubica
--     "entre la corrida anterior y esta". Dos cambios el mismo día = uno.
--   · QUIÉN: la consulta de Connekta no trae usuario ni fecha de modificación.
--     `externo` significa "no lo mandó el portal", no "lo hizo tal persona".
-- ---------------------------------------------------------------------------

-- ---------------------------------------------------------------------------
-- 1. pp_siesa_envios — un intento de importar al conector de cotizaciones
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pp_siesa_envios (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- A quién: un lote es UNA sucursal destino (ver empujarLote).
  cuenta_id           BIGINT       REFERENCES pp_cuentas(id) ON DELETE RESTRICT,
  id_tercero          VARCHAR(15),
  sucursal            VARCHAR(3),

  -- Qué: las líneas del lote y, por cada una, lo que se propuso. `items` es una
  -- foto al momento del envío: la línea puede reintentarse y cambiar después.
  solicitud_ids       BIGINT[]     NOT NULL DEFAULT '{}',
  linea_ids           BIGINT[]     NOT NULL DEFAULT '{}',
  renglones           INTEGER      NOT NULL DEFAULT 0,
  items               JSONB        NOT NULL DEFAULT '[]'::jsonb,

  -- Contra qué conector y qué ambiente. Hoy el conector escribe en QA a
  -- propósito (PENDIENTES §1.4): sin esta columna, una fila "aplicado" de QA se
  -- leería como un precio de producción.
  conector            TEXT,
  destino             VARCHAR(12)  NOT NULL DEFAULT 'desconocido',
  sandbox             BOOLEAN      NOT NULL DEFAULT false,

  estado              VARCHAR(16)  NOT NULL DEFAULT 'enviando',
  http_status         INTEGER,
  payload             JSONB,
  respuesta           JSONB,
  error               TEXT,
  -- [{linea_id, estado, motivo}] — la relectura, línea por línea.
  verificaciones      JSONB,

  enviado_por         TEXT,
  enviado_por_nombre  TEXT,
  enviado_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
  respondido_at       TIMESTAMPTZ,
  duracion_ms         INTEGER,

  -- true = reconstruida en esta migración desde el último intento de la línea.
  -- Los intentos anteriores a ese se perdieron: no se inventan.
  historico           BOOLEAN      NOT NULL DEFAULT false
);

ALTER TABLE pp_siesa_envios DROP CONSTRAINT IF EXISTS pp_siesa_envios_estado_valido;
ALTER TABLE pp_siesa_envios ADD CONSTRAINT pp_siesa_envios_estado_valido
  CHECK (estado IN (
    'enviando',       -- salió el POST y no hay respuesta todavía (o la función murió)
    'aceptado',       -- SIESA respondió OK; la relectura está en curso o se cortó
    'aplicado',       -- aceptado y la relectura lo confirmó
    'no_verificable', -- aceptado y no se pudo releer (hoy: siempre, por QA vs PROD)
    'incierto',       -- aceptado y la relectura lo contradice
    'rechazado',      -- el ERP lo rechazó: no quedó nada escrito
    'sin_respuesta',  -- se cortó la red / timeout: PUDO haber entrado
    'no_enviado',     -- no salió de acá (validación o configuración)
    'sandbox'         -- PROVEEDORES_SANDBOX: se armó y no se mandó
  ));

ALTER TABLE pp_siesa_envios DROP CONSTRAINT IF EXISTS pp_siesa_envios_destino_valido;
ALTER TABLE pp_siesa_envios ADD CONSTRAINT pp_siesa_envios_destino_valido
  CHECK (destino IN ('qa', 'produccion', 'desconocido'));

COMMENT ON TABLE pp_siesa_envios IS
  'Un intento de importar cotizaciones al conector de SIESA, salga bien o mal. '
  'Append-only en la práctica: solo se actualiza el MISMO intento al recibir la '
  'respuesta y la relectura. Ver sql/013.';

CREATE INDEX IF NOT EXISTS idx_pp_siesa_envios_fecha  ON pp_siesa_envios(enviado_at DESC);
CREATE INDEX IF NOT EXISTS idx_pp_siesa_envios_cuenta ON pp_siesa_envios(id_tercero, sucursal);
CREATE INDEX IF NOT EXISTS idx_pp_siesa_envios_lineas ON pp_siesa_envios USING GIN (linea_ids);
-- Lo que hay que mirar primero.
CREATE INDEX IF NOT EXISTS idx_pp_siesa_envios_atencion
  ON pp_siesa_envios(enviado_at DESC)
  WHERE estado IN ('enviando', 'aceptado', 'incierto', 'rechazado', 'sin_respuesta', 'no_enviado');

-- ---------------------------------------------------------------------------
-- 2. pp_siesa_cambios — una diferencia entre dos corridas del snapshot
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS pp_siesa_cambios (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  -- La ventana en la que pasó: después de `corrida_anterior_at` y antes de
  -- `detectado_at`. Es todo lo que el snapshot puede afirmar.
  detectado_at        TIMESTAMPTZ  NOT NULL,
  corrida_anterior_at TIMESTAMPTZ,

  clave               TEXT         NOT NULL,
  clave_item          TEXT         NOT NULL,
  id_tercero          VARCHAR(15)  NOT NULL,
  nit                 VARCHAR(15),
  sucursal            VARCHAR(3)   NOT NULL,
  item                INTEGER      NOT NULL,
  descripcion_item    TEXT,
  unidad_medida       VARCHAR(4)   NOT NULL,
  fecha_activacion    DATE         NOT NULL,

  tipo                VARCHAR(10)  NOT NULL,
  -- Qué cambió en una `modificada`: subconjunto de {precio, impuestos, descuentos}.
  campos              TEXT[]       NOT NULL DEFAULT '{}',
  antes               JSONB,       -- {precio, impuestos, descuentos}; NULL en altas
  despues             JSONB,       -- ídem; NULL en bajas

  -- portal = coincide con un envío nuestro aceptado; externo = no.
  origen              VARCHAR(10)  NOT NULL,
  envio_id            BIGINT       REFERENCES pp_siesa_envios(id) ON DELETE SET NULL
);

ALTER TABLE pp_siesa_cambios DROP CONSTRAINT IF EXISTS pp_siesa_cambios_tipo_valido;
ALTER TABLE pp_siesa_cambios ADD CONSTRAINT pp_siesa_cambios_tipo_valido
  CHECK (tipo IN ('alta', 'modificada', 'baja'));

ALTER TABLE pp_siesa_cambios DROP CONSTRAINT IF EXISTS pp_siesa_cambios_origen_valido;
ALTER TABLE pp_siesa_cambios ADD CONSTRAINT pp_siesa_cambios_origen_valido
  CHECK (origen IN ('portal', 'externo'));

COMMENT ON TABLE pp_siesa_cambios IS
  'Diferencias en las cotizaciones de SIESA detectadas por el snapshot diario. '
  'Resolución de un día y sin autor: ver la cabecera de sql/013.';

CREATE INDEX IF NOT EXISTS idx_pp_siesa_cambios_fecha  ON pp_siesa_cambios(detectado_at DESC);
CREATE INDEX IF NOT EXISTS idx_pp_siesa_cambios_cuenta ON pp_siesa_cambios(id_tercero, sucursal);
CREATE INDEX IF NOT EXISTS idx_pp_siesa_cambios_item   ON pp_siesa_cambios(item);

