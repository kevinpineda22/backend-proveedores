ALTER TABLE pp_siesa_envios  ENABLE ROW LEVEL SECURITY;
ALTER TABLE pp_siesa_cambios ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------------------------
-- 4. Historia: el último intento de cada línea que llegó a empujarse.
--
-- Una fila por LÍNEA (no por lote): los lotes viejos no quedaron registrados
-- como tales y reagruparlos por fecha sería adivinar. `historico = true` para
-- que la pantalla lo diga. El ambiente queda 'desconocido': no se guardó.
-- Idempotente: no reinserta una línea que ya tiene fila histórica.
-- ---------------------------------------------------------------------------
INSERT INTO pp_siesa_envios (
  cuenta_id, id_tercero, sucursal, solicitud_ids, linea_ids, renglones, items,
  destino, sandbox, estado, payload, respuesta, error, verificaciones,
  enviado_por, enviado_at, historico
)
SELECT
  l.cuenta_destino_id,
  split_part(l.clave_item, '|', 2),
  split_part(l.clave_item, '|', 3),
  ARRAY[l.solicitud_id],
  ARRAY[l.id],
  1,
  jsonb_build_array(jsonb_build_object(
    'linea_id', l.id,
    'solicitud_id', l.solicitud_id,
    'clave', l.clave_item || '|' || l.fecha_activacion::text,
    'item', l.item,
    'descripcion_item', l.descripcion_item,
    'unidad_medida', l.unidad_medida,
    'fecha_activacion', l.fecha_activacion,
    'precio_actual', l.precio_actual,
    'precio_propuesto', l.precio_propuesto,
    'origen', l.origen
  )),
  'desconocido',
  COALESCE((l.siesa_respuesta->>'sandbox')::boolean, false),
  CASE
    WHEN COALESCE((l.siesa_respuesta->>'sandbox')::boolean, false) THEN 'sandbox'
    WHEN l.estado = 'incierto' THEN 'incierto'
    WHEN l.estado = 'aplicada' AND l.siesa_verificacion->>'estado' = 'confirmado' THEN 'aplicado'
    WHEN l.estado = 'aplicada' THEN 'no_verificable'
    WHEN l.estado = 'fallida' AND l.siesa_respuesta->>'origen' = 'local' THEN 'no_enviado'
    WHEN l.estado = 'fallida' AND l.siesa_respuesta->>'origen' = 'sin_respuesta' THEN 'sin_respuesta'
    WHEN l.estado = 'fallida' THEN 'rechazado'
    ELSE 'aceptado'
  END,
  l.siesa_payload,
  l.siesa_respuesta,
  CASE WHEN l.estado = 'fallida' THEN l.siesa_respuesta->>'error' END,
  CASE WHEN l.siesa_verificacion IS NOT NULL THEN
    jsonb_build_array(jsonb_build_object(
      'linea_id', l.id,
      'estado', l.siesa_verificacion->>'estado',
      'motivo', l.siesa_verificacion->>'motivo'
    ))
  END,
  l.resuelto_por,
  COALESCE(l.siesa_aplicado_at, l.resuelto_at, l.updated_at),
  true
FROM pp_solicitud_lineas l
WHERE (l.siesa_payload IS NOT NULL OR l.siesa_respuesta IS NOT NULL)
  AND NOT EXISTS (
    SELECT 1 FROM pp_siesa_envios e WHERE e.historico AND e.linea_ids = ARRAY[l.id]
  );

