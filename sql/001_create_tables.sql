-- =============================================================================
-- APPEND-ONLY de verdad
--
-- Quitar la política de UPDATE en RLS no alcanza: el backend se conecta con la
-- SERVICE KEY, que pasa por encima de RLS. O sea que un bug nuestro podría editar
-- una firma sin que nada lo frene.
--
-- Un trigger sí ata a todos, service key incluida. Una firma que se puede editar
-- no es una firma, y una auditoría que se puede reescribir no es una auditoría.
-- =============================================================================

CREATE OR REPLACE FUNCTION pp_solo_insertar() RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION 'La tabla % es append-only: no admite % (intento sobre id=%)',
    TG_TABLE_NAME, TG_OP, COALESCE(OLD.id::text, '?');
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_pp_firmas_append_only ON pp_firmas;
CREATE TRIGGER trg_pp_firmas_append_only
  BEFORE UPDATE OR DELETE ON pp_firmas
  FOR EACH ROW EXECUTE FUNCTION pp_solo_insertar();

DROP TRIGGER IF EXISTS trg_pp_auditoria_append_only ON pp_auditoria;
CREATE TRIGGER trg_pp_auditoria_append_only
  BEFORE UPDATE OR DELETE ON pp_auditoria
  FOR EACH ROW EXECUTE FUNCTION pp_solo_insertar();

-- ---------------------------------------------------------------------------
-- updated_at automático
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION pp_touch_updated_at() RETURNS trigger AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_pp_proveedores_touch ON pp_proveedores;
CREATE TRIGGER trg_pp_proveedores_touch BEFORE UPDATE ON pp_proveedores
  FOR EACH ROW EXECUTE FUNCTION pp_touch_updated_at();

DROP TRIGGER IF EXISTS trg_pp_cuentas_touch ON pp_cuentas;
CREATE TRIGGER trg_pp_cuentas_touch BEFORE UPDATE ON pp_cuentas
  FOR EACH ROW EXECUTE FUNCTION pp_touch_updated_at();

DROP TRIGGER IF EXISTS trg_pp_solicitudes_touch ON pp_solicitudes_precio;
CREATE TRIGGER trg_pp_solicitudes_touch BEFORE UPDATE ON pp_solicitudes_precio
  FOR EACH ROW EXECUTE FUNCTION pp_touch_updated_at();

-- =============================================================================
-- RLS — la red debajo del trapecio
--
-- El aislamiento REAL lo hace el middleware del backend, que deriva el cuenta_id
-- del JWT (ARQUITECTURA §5). Esto es la segunda capa: el frontend tiene sesión
-- de Supabase con la anon key, así que si alguien consulta las tablas
-- directamente —o si mañana un endpoint se escribe sin filtro— la base corta.
--
-- Un proveedor viendo los precios de otro no es un bug menor: es un problema
-- legal. Por eso van dos capas y no una.
-- =============================================================================

ALTER TABLE pp_proveedores        ENABLE ROW LEVEL SECURITY;
ALTER TABLE pp_cuentas            ENABLE ROW LEVEL SECURITY;
ALTER TABLE pp_invitaciones       ENABLE ROW LEVEL SECURITY;
ALTER TABLE pp_cotizaciones       ENABLE ROW LEVEL SECURITY;
ALTER TABLE pp_firmas             ENABLE ROW LEVEL SECURITY;
ALTER TABLE pp_solicitudes_precio ENABLE ROW LEVEL SECURITY;
ALTER TABLE pp_auditoria          ENABLE ROW LEVEL SECURITY;

-- Sin políticas, RLS niega TODO. Cada permiso de abajo es explícito y mínimo.

/**
 * La cuenta del usuario que está consultando.
 *
 * SECURITY DEFINER para poder leer pp_cuentas sin caer en la recursión de
 * evaluar la política de pp_cuentas dentro de la política de pp_cuentas.
 * STABLE para que Postgres la evalúe una vez por consulta y no por fila.
 */
CREATE OR REPLACE FUNCTION pp_cuenta_actual() RETURNS BIGINT AS $$
  SELECT id FROM pp_cuentas
   WHERE user_id = auth.uid()
     AND estado = 'activo'
   LIMIT 1;
$$ LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public;

-- --- pp_cuentas: el proveedor ve SU cuenta y nada más -----------------------
DROP POLICY IF EXISTS pp_cuentas_propia ON pp_cuentas;
CREATE POLICY pp_cuentas_propia ON pp_cuentas
  FOR SELECT TO authenticated
  USING (user_id = auth.uid());

-- --- pp_cotizaciones: solo las de su NIT+sucursal ---------------------------
DROP POLICY IF EXISTS pp_cotizaciones_propias ON pp_cotizaciones;
CREATE POLICY pp_cotizaciones_propias ON pp_cotizaciones
  FOR SELECT TO authenticated
  USING (
    EXISTS (
      SELECT 1 FROM pp_cuentas c
       WHERE c.id = pp_cuenta_actual()
         AND c.nit = pp_cotizaciones.nit
         AND c.sucursal = pp_cotizaciones.sucursal
    )
  );

-- --- pp_solicitudes_precio: solo las propias, y solo lectura ----------------
-- La escritura pasa SIEMPRE por el backend: es el único lugar donde se valida el
-- tope contra el precio que el servidor leyó de SIESA. Un INSERT directo desde el
-- navegador se saltearía esa validación entera.
DROP POLICY IF EXISTS pp_solicitudes_propias ON pp_solicitudes_precio;
CREATE POLICY pp_solicitudes_propias ON pp_solicitudes_precio
  FOR SELECT TO authenticated
  USING (cuenta_id = pp_cuenta_actual());

-- --- pp_firmas: el proveedor ve las suyas, no las escribe desde el cliente --
DROP POLICY IF EXISTS pp_firmas_propias ON pp_firmas;
CREATE POLICY pp_firmas_propias ON pp_firmas
  FOR SELECT TO authenticated
  USING (cuenta_id = pp_cuenta_actual());

-- --- pp_proveedores, pp_invitaciones, pp_auditoria: SIN política ------------
-- Deliberado. `pp_proveedores` guarda `porcentaje_max`: el tope es información de
-- configuración interna, y el proveedor solo necesita conocerlo en el momento en
-- que lo choca — el 422 se lo dice con el número exacto. `pp_invitaciones` guarda
-- hashes de token. `pp_auditoria` es el registro de todos. Ninguna se expone al
-- cliente: se leen únicamente con la service key, desde el backend.
